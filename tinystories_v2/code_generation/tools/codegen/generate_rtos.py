#!/usr/bin/env python3
"""
generate_rtos.py — Generate RTOS task + API + CMake from te-comp manifest.

Called automatically by te-comp after engine emission, or standalone:

    python3 generate_rtos.py manifest.json --rtos freertos --output-dir output/
    python3 generate_rtos.py manifest.json --rtos baremetal --output-dir output/

Reads a manifest JSON (written by te-comp) and stamps out:
    inference_task.c   — RTOS task or bare-metal wrapper
    inference_api.h    — Public API header
    CMakeLists.txt     — Drop-in CMake library

No external dependencies (no Jinja2). Uses Python str.format() on .tpl files.
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


def load_manifest(path: str) -> dict:
    """Load and validate a manifest JSON file."""
    with open(path) as f:
        m = json.load(f)

    # Validate required top-level keys
    required = ["model_name", "input", "output", "memory", "files"]
    missing = [k for k in required if k not in m]
    if missing:
        print(f"ERROR: manifest missing required keys: {missing}", file=sys.stderr)
        sys.exit(1)

    return m


def dtype_to_ctype(dtype: str) -> str:
    """Map manifest dtype string to a C type name."""
    mapping = {
        "int8":    "int8_t",
        "int16":   "int16_t",
        "int32":   "int32_t",
        "int64":   "int64_t",
        "float16": "uint16_t",  # no native C float16; store as uint16
        "float32": "float",
    }
    return mapping.get(dtype, "int8_t")


def build_template_vars(manifest: dict) -> dict:
    """Build the flat dictionary of template variables from the manifest."""
    m = manifest
    name = m["model_name"]

    in_dtype = m["input"].get("dtype", "int8")
    out_dtype = m["output"].get("dtype", "int8")

    # Flatten nested dicts into template-friendly flat keys
    v = {
        # Identity
        "model_name":         name,
        "model_description":  m.get("model_description", name),
        "NAME":               name.upper(),

        # Input
        "input_shape_str":    ", ".join(str(d) for d in m["input"]["shape"]),
        "input_size_bytes":   m["input"]["size_bytes"],
        "input_dtype":        in_dtype,
        "input_c_type":       dtype_to_ctype(in_dtype),

        # Output
        "output_shape_str":   ", ".join(str(d) for d in m["output"]["shape"]),
        "output_size_bytes":  m["output"]["size_bytes"],
        "output_dtype":       out_dtype,
        "output_c_type":      dtype_to_ctype(out_dtype),

        # Memory
        "arena_size_bytes":   m["memory"]["arena_size_bytes"],
        "weights_flash_bytes": m["memory"]["weights_flash_bytes"],
        "scratch_size_bytes": m["memory"].get("scratch_size_bytes", 0),
        "peak_sram_bytes":    m["memory"]["peak_sram_bytes"],

        # Performance
        "total_macs":         m.get("performance", {}).get("total_macs", 0),
        "estimated_cycles":   m.get("performance", {}).get("estimated_cycles", 0),
        "clock_mhz":          m.get("performance", {}).get("target_clock_mhz", 170),
        "estimated_us":       m.get("performance", {}).get("estimated_us", 0),

        # Layers
        "num_layers":         len(m.get("layers", [])),

        # Files
        "engine_source":      m["files"]["engine_source"],
        "engine_header":      m["files"]["engine_header"],
        "weights_header":     m["files"]["weights_header"],

        # Compiler
        "compiler_version":   m.get("compiler", {}).get("version", "0.1.0"),
        "target":             m.get("compiler", {}).get("target", "cortex-m4"),

        # Generated
        "header_guard":       f"{name.upper()}_INFERENCE_API_H",
        "file_banner":        "Auto-generated by te-comp",

        # FreeRTOS defaults
        "default_priority":   3,
        "stack_size_bytes":   max(2048, m["memory"]["peak_sram_bytes"] + 1024),
    }

    return v


def render_template(template_path: str, variables: dict) -> str:
    """Render a .tpl file by substituting {variables}.

    Uses str.format_map with a SafeDict so that unknown keys (like CMake
    ${...} variables) pass through unchanged.
    """
    with open(template_path) as f:
        template = f.read()

    return template.format_map(SafeDict(variables))


class SafeDict(dict):
    """Dict subclass that returns '{key}' for missing keys.

    This prevents str.format_map from crashing on CMake variables like
    ${CMAKE_CURRENT_SOURCE_DIR} which we don't want to substitute.
    """
    def __missing__(self, key):
        return "{" + key + "}"


def generate(manifest_path: str, rtos: str, output_dir: str, verbose: bool = False):
    """Main generation entry point."""
    manifest = load_manifest(manifest_path)
    variables = build_template_vars(manifest)

    # Locate template directory
    script_dir = Path(__file__).parent
    template_dir = script_dir / "templates" / rtos

    if not template_dir.is_dir():
        available = [d.name for d in (script_dir / "templates").iterdir() if d.is_dir()]
        print(f"ERROR: unknown RTOS target '{rtos}'. Available: {available}", file=sys.stderr)
        sys.exit(1)

    # Create output directory
    os.makedirs(output_dir, exist_ok=True)

    # Render each template
    templates = {
        "inference_task.c.tpl": "inference_task.c",
        "inference_api.h.tpl":  "inference_api.h",
        "CMakeLists.txt.tpl":   "CMakeLists.txt",
    }

    generated_files = []
    for tpl_name, out_name in templates.items():
        tpl_path = template_dir / tpl_name
        if not tpl_path.exists():
            if verbose:
                print(f"  SKIP {tpl_name} (not found in {template_dir})")
            continue

        rendered = render_template(str(tpl_path), variables)
        out_path = os.path.join(output_dir, out_name)

        with open(out_path, "w") as f:
            f.write(rendered)

        generated_files.append(out_path)
        if verbose:
            print(f"  EMIT {out_path}")

    return generated_files


def main():
    parser = argparse.ArgumentParser(
        description="Generate RTOS inference task from te-comp manifest",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s manifest.json --rtos freertos -o output/
  %(prog)s manifest.json --rtos baremetal -o output/
  %(prog)s manifest.json --list-rtos

Supported RTOS targets: freertos, baremetal
        """,
    )
    parser.add_argument("manifest", help="Path to manifest.json from te-comp")
    parser.add_argument("--rtos", default="freertos",
                        help="RTOS target (default: freertos)")
    parser.add_argument("-o", "--output-dir", default=".",
                        help="Output directory (default: current dir)")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="Print generated file paths")
    parser.add_argument("--list-rtos", action="store_true",
                        help="List available RTOS templates and exit")

    args = parser.parse_args()

    if args.list_rtos:
        script_dir = Path(__file__).parent
        template_dir = script_dir / "templates"
        targets = [d.name for d in template_dir.iterdir() if d.is_dir()]
        print("Available RTOS targets:", ", ".join(sorted(targets)))
        sys.exit(0)

    files = generate(args.manifest, args.rtos, args.output_dir, args.verbose)

    print(f"Generated {len(files)} files for '{args.rtos}' in {args.output_dir}/")
    for f in files:
        print(f"  {f}")


if __name__ == "__main__":
    main()
